"""
Chat Module — Generate Conversations Between Agents
====================================================
When two agents are at the same location and both are free,
they can start a conversation. The LLM generates what each
agent says based on their personality and relationship.

Two conversation types:
- small_talk: 1-5 rounds, casual greeting or quick exchange
- deep_talk: 6-20 rounds, meaningful conversation

Each round = one message from each agent.
One round = 2 minutes of game time.

Connection to the paper:
    Section 4.5 — "Agents engage in conversations with each other.
    The dialogue is generated by the LLM based on the agents'
    personalities and their relationship."
"""
import datetime
from agent.prompts import get_prompts


def generate_round(persona, other_persona, llm_client):
    """
    Generate one round of conversation between two agents.

    Each agent generates one message. The conversation is stored
    in both agents' chat_history.

    Args:
        persona: the agent generating the message
        other_persona: the other agent in the conversation
        llm_client: API client for text generation

    Returns:
        dict with {"from": name, "msg": message}
    """
    prompts = get_prompts()

    # Format chat history so far
    history_text = _format_history(persona.scratch.chat_history)

    # Build the prompt
    prompt = prompts.CHAT_PROMPT.format(
        identity=persona.scratch.get_str_iss(),
        my_action=persona.scratch.act_description or "doing something",
        other_name=other_persona.name,
        other_action=other_persona.scratch.act_description or "doing something",
        chat_type=persona.scratch.chat_type or "small_talk",
        current_round=persona.scratch.chat_total_rounds - persona.scratch.chat_rounds_left + 1,
        total_rounds=persona.scratch.chat_total_rounds,
        chat_history=history_text if history_text else "(start of conversation)"
    )

    response = llm_client.generate(prompt, system_prompt=prompts.SYSTEM_PROMPT)
    if not response:
        return None

    # Parse the message
    message = _parse_message(response)

    # Store in chat history
    entry = {"from": persona.name, "msg": message}
    persona.scratch.chat_history.append(entry)

    return entry


